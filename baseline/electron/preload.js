'use strict'
const { contextBridge, ipcRenderer } = require('electron')

const on = (channel) => (handler) => {
  const listener = (_event, payload) => handler(payload)
  ipcRenderer.on(channel, listener)
  return () => ipcRenderer.removeListener(channel, listener)
}

contextBridge.exposeInMainWorld('yue', {
  state: () => ipcRenderer.invoke('app:state'),
  checkSetup: () => ipcRenderer.invoke('setup:check'),
  location: () => ipcRenderer.invoke('setup:location'),
  pickLocation: () => ipcRenderer.invoke('setup:pick-location'),
  moveModels: () => ipcRenderer.invoke('settings:move-models'),
  moveSongs: () => ipcRenderer.invoke('settings:move-songs'),
  pickExport: () => ipcRenderer.invoke('settings:pick-export'),
  onSongsMoveProgress: on('songs:move-progress'),
  runSetup: () => ipcRenderer.invoke('setup:run'),
  listSongs: () => ipcRenderer.invoke('songs:list'),
  projects: () => ipcRenderer.invoke('projects:list'),
  selectProject: (name) => ipcRenderer.invoke('projects:select', name),
  createProject: (name) => ipcRenderer.invoke('projects:create', name),
  renameProject: (from, to) => ipcRenderer.invoke('projects:rename', { from, to }),
  generate: (payload) => ipcRenderer.invoke('song:generate', payload),
  resume: (dir) => ipcRenderer.invoke('song:resume', dir),
  score: (dir) => ipcRenderer.invoke('song:score', dir),
  checkScore: (text) => ipcRenderer.invoke('score:check', text),
  videoSettings: () => ipcRenderer.invoke('video:settings'),
  saveVideoSettings: (video) => ipcRenderer.invoke('video:save-settings', video),
  videoPrepare: (request) => ipcRenderer.invoke('video:prepare', request),
  videoBackground: (kind) => ipcRenderer.invoke('video:background', kind),
  videoStart: (request) => ipcRenderer.invoke('video:start', request),
  videoFrame: (jobId, index, data) => ipcRenderer.invoke('video:frame', jobId, index, data),
  videoLayer: (jobId, data) => ipcRenderer.invoke('video:layer', jobId, data),
  videoFinish: (jobId) => ipcRenderer.invoke('video:finish', jobId),
  videoCancel: (jobId) => ipcRenderer.invoke('video:cancel', jobId),
  videoCompare: (request) => ipcRenderer.invoke('video:compare', request),
  onVideoProgress: on('video:progress'),
  onVideoFailed: on('video:failed'),
  openScore: () => ipcRenderer.invoke('score:open'),
  convertMidi: (choice) => ipcRenderer.invoke('score:convert', choice),
  render: (dir, abc, title) => ipcRenderer.invoke('song:render', { dir, abc, title }),
  cancel: () => ipcRenderer.invoke('song:cancel'),
  queue: () => ipcRenderer.invoke('queue:list'),
  queueRemove: (jobId) => ipcRenderer.invoke('queue:remove', jobId),
  queueRetry: (jobId) => ipcRenderer.invoke('queue:retry', jobId),
  queueMove: (jobId, delta) => ipcRenderer.invoke('queue:move', { jobId, delta }),
  queueReorder: (ids) => ipcRenderer.invoke('queue:reorder', ids),
  reorderSongs: (folders) => ipcRenderer.invoke('songs:reorder', folders),
  importSongs: () => ipcRenderer.invoke('songs:import'),
  queuePause: (value) => ipcRenderer.invoke('queue:pause', value),
  queueDismiss: (jobId) => ipcRenderer.invoke('queue:dismiss', jobId),
  queueClear: () => ipcRenderer.invoke('queue:clear'),
  onQueue: on('queue:update'),
  onJobStarted: on('job:started'),
  remove: (dir) => ipcRenderer.invoke('song:delete', dir),
  rename: (dir, title) => ipcRenderer.invoke('song:rename', { dir, title }),
  reveal: (dir) => ipcRenderer.invoke('song:reveal', dir),
  exportSong: (dir, title, format) => ipcRenderer.invoke('song:export', { dir, title, format }),
  exportAlbum: (options) => ipcRenderer.invoke('album:export', options),
  onAlbumProgress: on('album:progress'),
  presets: () => ipcRenderer.invoke('presets:list'),
  savePreset: (preset) => ipcRenderer.invoke('presets:save', preset),
  deletePreset: (name) => ipcRenderer.invoke('presets:delete', name),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  compact: () => ipcRenderer.invoke('songs:compact'),
  open: (target) => ipcRenderer.invoke('shell:open', target),
  openLog: () => ipcRenderer.invoke('log:open'),
  log: (text) => ipcRenderer.invoke('ui:log', text),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: (info) => ipcRenderer.invoke('update:install', info),
  onUpdateProgress: on('update:progress'),
  onStats: on('system:stats'),
  onSetupStep: on('setup:step'),
  onSetupProgress: on('setup:progress'),
  onSetupLog: on('setup:log'),
  onJobEvent: on('job:event'),
  onJobDone: on('job:done'),
  onJobError: on('job:error'),
  onWorkerLog: on('worker:log')
})
