const { _electron } = require('playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const data = path.join(root, '.runtime', 'timeline-' + Date.now());
const evidence = path.join(root, 'evidence/studio');
fs.mkdirSync(data, { recursive: true });
const checks = [], errors = []; let app;
function ff(args) { execFileSync('ffmpeg', ['-v', 'error', '-nostdin', ...args], { windowsHide: true }); }
async function main() {
  const video = path.join(data, 'motion.mp4'), audio = path.join(data, 'music.wav');
  ff(['-f', 'lavfi', '-i', 'testsrc2=size=640x360:rate=30:duration=6', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=6', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', video]);
  ff(['-f', 'lavfi', '-i', 'sine=frequency=880:duration=6', '-af', 'volume=0.7', '-c:a', 'pcm_s16le', audio]);
  const env = { ...process.env, OCUT_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE;
  app = await _electron.launch({ executablePath: path.join(root, 'dist/studio/O-CUT.exe'), env });
  const page = await app.firstWindow(); page.on('pageerror', e => errors.push(e.message));
  page.on('console', msg => { if (msg.type() === 'error') fs.appendFileSync(path.join(evidence, 'timeline-console.log'), msg.text() + '\n'); });
  app.process().stderr.on('data', b => fs.appendFileSync(path.join(evidence, 'timeline-stderr.log'), b));
  await page.waitForFunction(() => document.querySelector('#status').textContent === '프로젝트 준비됨');
  await app.evaluate(({ dialog }, files) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: files }); }, [video, audio]);
  await page.locator('#importMedia').click();
  await page.waitForFunction(() => document.querySelectorAll('.media-card').length === 2, null, { timeout: 60000 });
  const imported = await page.evaluate(() => window.ocut.state());
  assert.ok(Object.values(imported.assets).every(a => a.waveform.peaks.some(x => x > 0)));
  checks.push('actual video/audio import, PCM waveform, thumbnails');
  await page.locator('.media-add').nth(0).click(); await page.waitForFunction(() => document.querySelectorAll('.clip').length === 1);
  await page.locator('.media-add').nth(1).click(); await page.waitForFunction(() => document.querySelectorAll('.clip').length === 2);
  await page.locator('#play').click(); await page.waitForFunction(() => Number(document.querySelector('#timecode').textContent.slice(3)) > .5);
  await page.locator('#play').click();
  const pixels = await page.evaluate(() => { const ctx = document.querySelector('#preview').getContext('2d'); const b = ctx.getImageData(0, 0, 1920, 1080).data; return { red: [...b.slice(0, 4)], varied: b.some((x, i) => i % 4 === 0 && x > 180) }; });
  assert.equal(pixels.varied, true); checks.push('actual realtime playback and decoded canvas video');
  const head = await page.locator('#ruler').boundingBox();
  await page.locator('.clip.video').click({ position: { x: 40, y: 15 } });
  await page.mouse.click(head.x + 2 * 70, head.y + 10);
  await page.locator('#split').click(); await page.waitForFunction(() => document.querySelectorAll('.clip').length === 3);
  let snapshot = await page.evaluate(() => window.ocut.state());
  assert.deepEqual(snapshot.project.clips.filter(c => c.type === 'video').map(c => c.duration), [2, 4]);
  await page.locator('#clipDuration').fill('2'); await page.locator('#clipForm button[type=submit]').click();
  await page.waitForFunction(() => state.project.clips.filter(c => c.type === 'video')[1].duration === 2);
  checks.push('UI playhead split and inspector trim');
  await page.locator('#addText').click(); await page.waitForFunction(() => !document.querySelector('#textField').hidden);
  await page.locator('#clipText').fill('O-CUT 첫 번째 장면'); await page.locator('#clipY').fill('300'); await page.locator('#clipForm button[type=submit]').click();
  await page.waitForFunction(() => state.project.clips.some(c => c.text === 'O-CUT 첫 번째 장면'));
  await page.locator('#undo').click(); await page.waitForFunction(() => document.querySelector('#clipText').value !== 'O-CUT 첫 번째 장면');
  await page.locator('#redo').click(); await page.waitForFunction(() => document.querySelector('#clipText').value === 'O-CUT 첫 번째 장면');
  checks.push('text edit undo redo through actual controls');
  await page.locator('#snap').click();
  let textBox = await page.locator('.clip.text').boundingBox();
  await page.mouse.move(textBox.x + 35, textBox.y + 18); await page.mouse.down(); await page.mouse.move(textBox.x + 105, textBox.y + 18, { steps: 6 }); await page.mouse.up();
  await page.waitForFunction(() => Math.abs(state.project.clips.find(c => c.type === 'text').startTime - 3) < .001);
  const rightHandle = await page.locator('.clip.text .trim-handle.right').boundingBox();
  await page.mouse.move(rightHandle.x + 3, rightHandle.y + 20); await page.mouse.down(); await page.mouse.move(rightHandle.x + 73, rightHandle.y + 20, { steps: 6 }); await page.mouse.up();
  await page.waitForFunction(() => Math.abs(state.project.clips.find(c => c.type === 'text').duration - 4) < .001);
  checks.push('actual pointer drag move and right edge trim');
  await page.locator('#undo').click(); await page.waitForFunction(() => state.project.clips.find(c => c.type === 'text').duration === 3);
  await page.locator('#undo').click(); await page.waitForFunction(() => state.project.clips.find(c => c.type === 'text').startTime === 2);
  await page.getByRole('button', { name: '텍스트 트랙 잠금', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#split').disabled);
  assert.equal(await page.locator('#clipText').isDisabled(), true);
  await page.getByRole('button', { name: '텍스트 트랙 잠금', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('#clipText').disabled);
  checks.push('track lock disables editing and unlock restores editing');
  const save = path.join(data, 'timeline.ocut');
  await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, save);
  await page.locator('#save').click(); await page.waitForFunction(() => document.querySelector('#saveState').textContent === '저장됨');
  await page.screenshot({ path: path.join(evidence, 'timeline-preview.png') });
  assert.deepEqual(errors, []); await app.close(); app = null;
  app = await _electron.launch({ executablePath: path.join(root, 'dist/studio/O-CUT.exe'), env });
  const reopened = await app.firstWindow(); await reopened.waitForFunction(() => document.querySelector('#status').textContent === '프로젝트 준비됨');
  await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, save);
  await reopened.locator('#openProject').click(); await reopened.waitForFunction(() => document.querySelectorAll('.clip').length === 4);
  assert.deepEqual((await reopened.evaluate(() => window.ocut.state())).project, JSON.parse(fs.readFileSync(save)));
  checks.push('app close relaunch project open restores exact timeline');
  await app.close(); app = null;
  fs.writeFileSync(path.join(evidence, 'timeline-qa.json'), JSON.stringify({ time: new Date().toISOString(), data, save, checks, errors, project: JSON.parse(fs.readFileSync(save)) }, null, 2));
  console.log('Timeline QA PASS:', checks.length, 'checks');
}
main().catch(async e => { fs.writeFileSync(path.join(evidence, 'timeline-failure.json'), JSON.stringify({ message: e.stack, data, checks, errors }, null, 2)); console.error(e); if (app) { await app.evaluate(({ app }) => app.exit()).catch(() => {}); } process.exitCode = 1; });
