const { _electron } = require('playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const data = path.join(root, '.runtime', 'shell-' + Date.now());
const evidence = path.join(root, 'evidence/studio');
fs.mkdirSync(data, { recursive: true });
const checks = [], errors = [];
let app;
async function main() {
  const env = { ...process.env, OCUT_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE;
  app = await _electron.launch({ executablePath: path.join(root, 'dist/studio/O-CUT.exe'), env });
  app.process().stderr.on('data', chunk => fs.appendFileSync(path.join(evidence, 'shell-stderr.log'), chunk));
  const page = await app.firstWindow(); page.on('pageerror', error => errors.push(error.message));
  await page.waitForFunction(() => document.querySelector('#status').textContent === '프로젝트 준비됨');
  assert.ok((await page.title()).includes('O-CUT'));
  assert.equal(await page.evaluate(() => typeof require), 'undefined');
  const security = await app.evaluate(({ BrowserWindow, app }) => ({ preferences: BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences(), userData: app.getPath('userData') }));
  assert.equal(security.preferences.sandbox, true); assert.equal(security.preferences.contextIsolation, true); assert.equal(security.preferences.nodeIntegration, false);
  checks.push('packaged O-CUT UI and isolated preload');
  await page.locator('#projectName').fill('나의 첫 O-CUT 영상');
  await page.locator('#projectForm button').click();
  await page.waitForFunction(() => document.querySelector('#documentTitle').textContent === '나의 첫 O-CUT 영상');
  await page.locator('#undo').click(); await page.waitForFunction(() => document.querySelector('#documentTitle').textContent === '새 프로젝트');
  await page.locator('#redo').click(); await page.waitForFunction(() => document.querySelector('#documentTitle').textContent === '나의 첫 O-CUT 영상');
  checks.push('settings apply undo redo');
  const target = path.join(data, 'project.ocut');
  await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, target);
  await page.locator('#save').click(); await page.waitForFunction(() => document.querySelector('#saveState').textContent === '저장됨');
  assert.equal(JSON.parse(fs.readFileSync(target)).name, '나의 첫 O-CUT 영상');
  await page.locator('#newProject').click(); await page.waitForFunction(() => document.querySelector('#documentTitle').textContent === '새 프로젝트');
  await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, target);
  await page.locator('#openProject').click(); await page.waitForFunction(() => document.querySelector('#documentTitle').textContent === '나의 첫 O-CUT 영상');
  checks.push('actual project save new open through UI');
  await page.screenshot({ path: path.join(evidence, 'shell-1540.png') });
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1100, 760));
  await page.waitForTimeout(150);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(evidence, 'shell-1100.png') });
  checks.push('minimum desktop width no document overflow');
  assert.deepEqual(errors, []);
  await app.close(); app = null;
  fs.writeFileSync(path.join(evidence, 'shell-qa.json'), JSON.stringify({ time: new Date().toISOString(), data, checks, errors, security }, null, 2));
  console.log('Shell UI QA PASS:', checks.length, 'checks');
}
main().catch(async error => { console.error(error); if (app) await app.close().catch(() => {}); process.exitCode = 1; });
